"""(U.grad) gradU of the curved analytic flows, as C++ by Sympy.

gradU(i, j) = dU_i/dx_j, and (U.grad) gradU(i, j) = sum_k U_k d/dx_k gradU(i, j).
Each block ends convective_terms in
src/interpol/expressions/Expr_<Flow>.hpp, for StokesSphere, BatchelorVortex,
BrinkmanCylinder and TaylorCouette: Sympy's common subexpressions as locals
w0, w1, ..., then the nine components into out. It reads the expression's
members and the locals, or arguments, its symbols name; the locals before it
(BatchelorVortex's d2ph, BrinkmanCylinder's frrr_r, TaylorCouette's strains)
are written by hand.

    python3 python/codegen/conv_gradu.py [stokes_sphere batchelor brinkman taylor_couette]

prints the blocks named, all by default, each to replace the one in its header.
"""
import sys
import sympy as sp
from sympy.printing.c import C99CodePrinter

X, Y, Z = sp.symbols("r_0 r_1 r_2", real=True)
x = (X, Y, Z)


def conv(U):
    J = sp.Matrix(3, 3, lambda i, j: sp.diff(U[i], x[j]))
    return sp.Matrix(3, 3, lambda i, j: sum(U[k] * sp.diff(J[i, j], x[k]) for k in range(3)))


def fsubs(expr, func, names):
    """func(...) and its derivatives by order: names[order]; for a function
    of two arguments, names maps (order in the first, order in the second)."""
    def order(t):
        d = t.expr if isinstance(t, sp.Subs) else t
        if len(d.expr.args) == 1:
            return sum(k for _, k in d.variable_count)
        return tuple(sum(k for v, k in d.variable_count if v == w) for w in d.expr.args)

    def is_d(t):
        d = t.expr if isinstance(t, sp.Subs) else t
        return isinstance(d, sp.Derivative) and getattr(d.expr, "func", None) == func
    expr = expr.replace(is_d, lambda t: sp.Symbol(names[order(t)]))
    expr = expr.replace(lambda t: isinstance(t, sp.Subs) and t.expr.is_Symbol, lambda t: t.expr)
    return expr.replace(lambda t: getattr(t, "func", None) == func,
                        lambda t: sp.Symbol(names[0 if len(t.args) == 1 else (0, 0)]))


class Printer(C99CodePrinter):
    """C with no pow: integer powers as products, halves through sqrt; the
    symbols in fields read as members of a struct, as fields[name]."""

    def __init__(self, fields=None):
        super().__init__()
        self.fields = fields or {}

    def _print_Symbol(self, expr):
        name = super()._print_Symbol(expr)
        return self.fields.get(name, name)

    def _print_Pow(self, expr):
        b, e = expr.as_base_exp()
        if e.is_Rational and e.q in (1, 2) and abs(e.p) <= 2 * 8:
            base = self.parenthesize(b, 1000)
            n = abs(e.p) // e.q
            parts = [base] * n + (["sqrt(%s)" % self._print(b)] if e.q == 2 else [])
            # parenthesised: the caller places it as a power, which binds tighter than * and /
            prod = "(%s)" % "*".join(parts) if len(parts) > 1 else parts[0]
            return "(1.0/%s)" % prod if e.p < 0 else prod
        return super()._print_Pow(expr)


def emit(M, fields=None):
    reps, (out,) = sp.cse([M], symbols=sp.numbered_symbols("w"), optimizations="basic")
    pr = Printer(fields)
    lines = ["    // (U.grad) gradU, generated by Sympy (python/codegen/conv_gradu.py)"]
    for s, e in reps:
        lines.append("    const double %s = %s;" % (s, pr.doprint(e)))
    lines.append("    out <<")
    lines.append(",\n".join("      " + pr.doprint(out[i, j]) for i in range(3) for j in range(3)) + ";")
    code = "\n".join(lines)
    # library calls the printer is to have written out
    calls = [f for f in ("pow(", "sin(", "cos(", "exp(") if f in code]
    assert not calls, "the block calls %s" % ", ".join(calls)
    return code


def stokes_sphere():
    R, u = sp.symbols("R u_inf", positive=True)
    r2 = X**2 + Y**2 + Z**2
    eta = R / sp.sqrt(r2)
    f_r = 1 + eta**3 / 2 - sp.Rational(3, 2) * eta
    f_t = -1 + eta**3 / 4 + sp.Rational(3, 4) * eta
    U = [X * Z / r2 * (f_r + f_t) * u, Y * Z / r2 * (f_r + f_t) * u, Z * Z / r2 * (f_r + f_t) * u - f_t * u]
    return emit(conv(U))


def batchelor():
    R1, R2, u0, q = sp.symbols("R1 R2 u0 q", positive=True)
    phi = sp.Function("phi")
    s2 = X**2 + Y**2
    U = [-u0 * Y * phi(s2 / R1**2) / R1, u0 * X * phi(s2 / R1**2) / R1, q * u0 * sp.exp(-s2 / R2**2)]
    C = fsubs(conv(U).doit(), phi, ["ph", "dph", "d2ph", "d3ph"]).subs(sp.exp(-s2 / R2**2), sp.Symbol("eta22"))
    return emit(C)


def brinkman():
    R, u = sp.symbols("R u_inf", positive=True)
    rho = sp.sqrt(X**2 + Y**2) / R
    f = sp.Function("f")
    t = sp.Symbol("t", positive=True)
    st, ct = Y / sp.sqrt(X**2 + Y**2), X / sp.sqrt(X**2 + Y**2)
    F, Fp = f(rho), sp.Derivative(f(t), t).subs(t, rho)
    U = [u * (st**2 * Fp + F * ct**2 / rho), u * st * ct * (-Fp + F / rho), sp.Integer(0)]
    return emit(fsubs(conv(U).doit(), f, ["f_r", "fr_r", "frr_r", "frrr_r"]))


def taylor_couette():
    kr, kz, K, a, c3, H = sp.symbols("kr kz K a c3 H", positive=True)
    s = sp.sqrt(X**2 + Y**2)
    E = sp.Function("E")
    q, p = kr * (s - 1), kz * Z
    F = sp.cos(p) + a * sp.cos(2 * p)
    G = sp.sin(p) + a * sp.sin(2 * p) / 2
    W = 1 - 4 * Z**2 / H**2
    A, B = K * kz, K * kr
    u_r = A * sp.sin(q) * F / s
    u_z = -B * sp.cos(q) * G / s
    u_t = E(s, Z) + c3 * sp.sin(q) * W
    c, sn = X / s, Y / s
    U = [u_r * c - u_t * sn, u_r * sn + u_t * c, u_z]
    C = fsubs(conv(U).doit(), E, {(0, 0): "eE", (1, 0): "Er", (0, 1): "Ez", (2, 0): "Err", (1, 1): "Erz", (0, 2): "Ezz"})
    # the angles' sines and cosines as the caller has them
    sq_, cq_, sp_, cp_ = sp.symbols("sq cq sp cp")
    C = C.subs({sp.sin(2 * p): 2 * sp_ * cp_, sp.cos(2 * p): 2 * cp_**2 - 1})
    C = C.subs({sp.sin(q): sq_, sp.cos(q): cq_, sp.sin(p): sp_, sp.cos(p): cp_})
    assert not C.atoms(sp.sin, sp.cos), C.atoms(sp.sin, sp.cos)
    # the point's quantities from the struct at; eE's second derivatives are locals
    at = ["r_0", "r_1", "r_2", "eE", "Er", "Ez", "sq", "cq", "sp", "cp"]
    return emit(C, {n: "at." + n for n in at})


if __name__ == "__main__":
    for w in sys.argv[1:] or ["stokes_sphere", "batchelor", "brinkman", "taylor_couette"]:
        print(globals()[w]())
        print()
