#include "Expr.hpp"

#ifndef __EXPR_STOKESSPHERE_HPP
#define __EXPR_STOKESSPHERE_HPP

class Expr_StokesSphere final : public Expr {
public:
  Expr_StokesSphere(const partrac::Params& expr_params) : Expr(expr_params) {
    R = expr_params.get<double>("R");
    mu = expr_params.get<double>("mu");
    Rho = expr_params.get<double>("rho");
    x0 = {expr_params.get<double>("x0"),
          expr_params.get<double>("y0"),
          expr_params.get<double>("z0")};
    u_inf = expr_params.get<double>("u_inf");
    p_inf = expr_params.get<double>("p_inf");
  };
  // Keys this expression reads
  static void add_params(partrac::Schema& s) {
    s.require<double>("R", "sphere radius");
    s.require<double>("u_inf", "far-field velocity");
    s.require<double>("mu", "viscosity");
    s.require<double>("p_inf", "pressure");
    s.require<double>("rho", "density");
    s.require<double>("x0", "centre x");
    s.require<double>("y0", "centre y");
    s.require<double>("z0", "centre z");
  };
  // Distance to the sphere, positive in the fluid
  bool has_wall() const { return true; };
  double sdf(const Vector3d &x) const { return (x-x0).norm() - R; };
  Vector3d sdf_grad(const Vector3d &x) const { return (x-x0).normalized(); };
  bool inside(const Vector3d &x, const double t __attribute__((unused))) {
    Vector3d r = x-x0;
    double r2 = r.squaredNorm();
    double R2 = R*R;
    bool _is_inside = r2 >= R2;
    return _is_inside;
  };
  void eval(const Vector3d &x, const double t __attribute__((unused)), PointValues& ptvals) {

    Vector3d r = x-x0;
    double r2 = r.squaredNorm();
    double R2 = R*R;

    double eta = R/sqrt(r2);
    double eta3 = pow(eta, 3);

    double f_r = 1.0 + 1./2. * eta3 - 3./2. * eta;
    double f_theta = -1.0 + 1./4. * eta3 + 3./4. * eta;

    double r7 = pow(r2, 7.0/2.0);

    ptvals.U = {r[0]*r[2]/r2 * (f_r + f_theta) * u_inf,
                r[1]*r[2]/r2 * (f_r + f_theta) * u_inf,
                r[2]*r[2]/r2 * (f_r + f_theta) * u_inf - f_theta * u_inf};
    ptvals.P = p_inf - 3.0/2.0 * mu * u_inf * r[2] * eta / r2;
    ptvals.Rho = Rho;

    // Hardcoded -- copied from consistency-checked Sympy code
    ptvals.gradU << (3.0/4.0)*R*r[2]*u_inf*(-2*pow(r[0], 2)*(R2 - r2) - pow(r[0], 2)*(3*R2 - r2) + r2*(R2 - r2))/r7,
                    (3.0/4.0)*R*r[0]*r[1]*r[2]*u_inf*(-5*R2 + 3*r2)/r7,
                    (3.0/4.0)*R*r[0]*u_inf*(-2*pow(r[2], 2)*(R2 - r2) - pow(r[2], 2)*(3*R2 - r2) + r2*(R2 - r2))/r7,
                    (3.0/4.0)*R*r[0]*r[1]*r[2]*u_inf*(-5*R2 + 3*r2)/r7,
                    (3.0/4.0)*R*r[2]*u_inf*(-2*pow(r[1], 2)*(R2 - r2) - pow(r[1], 2)*(3*R2 - r2) + r2*(R2 - r2))/r7,
                    (3.0/4.0)*R*r[1]*u_inf*(-2*pow(r[2], 2)*(R2 - r2) - pow(r[2], 2)*(3*R2 - r2) + r2*(R2 - r2))/r7,
                    (3.0/4.0)*R*r[0]*u_inf*(-2*pow(r[2], 2)*(R2 - r2) - pow(r[2], 2)*(3*R2 - r2) + r2*(R2 + r2))/r7,
                    (3.0/4.0)*R*r[1]*u_inf*(-2*pow(r[2], 2)*(R2 - r2) - pow(r[2], 2)*(3*R2 - r2) + r2*(R2 + r2))/r7,
                    (3.0/4.0)*R*r[2]*u_inf*(-2*pow(r[2], 2)*(R2 - r2) - pow(r[2], 2)*(3*R2 - r2) + 2*r2*(R2 - r2) + r2*(R2 + r2))/r7;
    if (convective)
      convective_terms(r[0], r[1], r[2], ptvals.convGradU);
  };
  // (U.grad) gradU, out of the hot eval
  __attribute__((noinline))
  void convective_terms(const double r_0, const double r_1, const double r_2, Matrix3d& out) const {
    // (U.grad) gradU, generated by Sympy (python/codegen/conv_gradu.py)
    const double w0 = ((r_1)*(r_1));
    const double w1 = ((R)*(R));
    const double w2 = ((r_0)*(r_0));
    const double w3 = ((r_2)*(r_2));
    const double w4 = w0 + w2 + w3;
    const double w5 = (1.0/(w4));
    const double w6 = w1*w5;
    const double w7 = 5*w6;
    const double w8 = w7 - 1;
    const double w9 = 3*w5;
    const double w10 = w2*w9;
    const double w11 = 3 - w7;
    const double w12 = 3*w6;
    const double w13 = w12 - 1;
    const double w14 = w13*w5;
    const double w15 = w14*w2;
    const double w16 = w2*w5;
    const double w17 = w6 - 1;
    const double w18 = 8*w17;
    const double w19 = 4*w15 + w16*w18;
    const double w20 = w11 + w19;
    const double w21 = (1.0/((w4)*(w4)*(w4)*(w4)));
    const double w22 = 3*R;
    const double w23 = w17*w22;
    const double w24 = w21*w23*w3;
    const double w25 = w24*(w10*w8 + w20);
    const double w26 = (1.0/((w4)*(w4)));
    const double w27 = w1*w26;
    const double w28 = 15*w27;
    const double w29 = -w10 + w2*w28;
    const double w30 = -15*w6;
    const double w31 = w30 + 9;
    const double w32 = w2*w24;
    const double w33 = w26*w3;
    const double w34 = w2*w33;
    const double w35 = -w18*w34;
    const double w36 = 2*w17;
    const double w37 = w14*w3;
    const double w38 = w3*w5;
    const double w39 = w36*w38 - w6;
    const double w40 = w37 + w39 + 1;
    const double w41 = 4*w13*w2*w26*w3 - w15 - w16*w36 + 3*w2*w26*w3*w8 - w35 - w40;
    const double w42 = (1.0/((w4)*sqrt(w4)));
    const double w43 = -((R)*(R)*(R))*w42 + 3*R*w17*w3*w42 - w22/sqrt(w4) + 4;
    const double w44 = w42*w43;
    const double w45 = (3.0/16.0)*R*((u_inf)*(u_inf));
    const double w46 = w0*w9;
    const double w47 = w0*w28 - w46;
    const double w48 = w0*w14;
    const double w49 = w0*w5;
    const double w50 = w18*w49 + 4*w48;
    const double w51 = w11 + w50;
    const double w52 = 4*w37;
    const double w53 = w3*w9;
    const double w54 = w53*w8;
    const double w55 = w18*w38;
    const double w56 = w54 + w55;
    const double w57 = w11 + w52 + w56;
    const double w58 = w43/((w4)*(w4)*sqrt(w4));
    const double w59 = w57*w58;
    const double w60 = r_0*w45;
    const double w61 = r_1*w60;
    const double w62 = w21*w23;
    const double w63 = w57*w62;
    const double w64 = w28*w3 - w53;
    const double w65 = w58*(w31 + w52 + w55 + w64);
    const double w66 = w23/((w4)*(w4)*(w4));
    const double w67 = r_2*w60;
    const double w68 = w24*(w46*w8 + w51);
    const double w69 = w0*w24;
    const double w70 = w0*w33;
    const double w71 = -w18*w70;
    const double w72 = 4*w0*w13*w26*w3 + 3*w0*w26*w3*w8 - w36*w49 - w40 - w48 - w71;
    const double w73 = r_1*r_2*w45;
    const double w74 = -w13;
    const double w75 = 4*w74;
    const double w76 = w62*(w38*w75 - w54 - w55 + w7 + 3);
    const double w77 = 4*w3*w5*w74 - w30 - w56 - 3;
    const double w78 = w58*w77;
    const double w79 = 1 - w12;
    const double w80 = 5*w27;
    const double w81 = w39 - 1;
    const double w82 = ((r_2)*(r_2)*(r_2)*(r_2));
    out <<
      w45*(w0*w25 + w32*(w19 + w29 + w31) + w41*w44),
      w61*(w24*(w47 + w51) + w25 + w59),
      w67*(w0*w63 + w41*w66 + w65),
      w61*(w24*(w20 + w29) + w59 + w68),
      w45*(w2*w68 + w44*w72 + w69*(w31 + w47 + w50)),
      w73*(w2*w63 + w65 + w66*w72),
      -w67*(w0*w76 + w66*(w10 + w2*w80 + w34*w75 + w35 - w38*(w29 + w79) + w81) + w78),
      -w73*(w2*w76 + w66*(w0*w80 - w38*(w47 + w79) + w46 + w70*w75 + w71 + w81) + w78),
      w45*(-w32*w77 + w42*w43*(4*w13*w26*w82 + 8*w17*w26*w82 - 10*w17*w38 + w3*w5*(w64 + w79) - w3*w80 - w52 - w53 - w79) - w69*w77);
  };
private:
  double R;  // Radius of sphere
  double mu;  // Viscosity
  Vector3d x0;  // Center of sphere
  double u_inf;  // Far-field velocity
  double p_inf;  // Far-field pressure
  double Rho;
};

#endif
